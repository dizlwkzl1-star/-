const cellPara = (text, o = {}) => new Paragraph({
  spacing: { before: 40, after: 40, line: 260 },
  alignment: o.align,
  children: [new TextRun({
    text: String(text), font: KO, size: o.size ?? 17,
    bold: o.bold, color: o.color ?? (o.head ? "FFFFFF" : "000000"),
  })],
});

function mkTable(widths, header, rows, opts = {}) {
  const sum = widths.reduce((a, b) => a + b, 0);
  const cols = widths.map(w => Math.round(w / sum * USABLE));
  // 반올림 오차를 마지막 열에서 보정
  cols[cols.length - 1] += USABLE - cols.reduce((a, b) => a + b, 0);

  const headRow = new TableRow({
    tableHeader: true,
    children: header.map((h, i) => new TableCell({
      width: { size: cols[i], type: WidthType.DXA },
      shading: { type: ShadingType.CLEAR, fill: HDR_BG, color: "auto" },
      margins: { top: 60, bottom: 60, left: 80, right: 80 },
      children: [cellPara(h, { bold: true, head: true, align: AlignmentType.CENTER })],
    })),
  });

  const bodyRows = rows.map((r, ri) => new TableRow({
    children: r.map((c, i) => {
      const warn = opts.warnRows && opts.warnRows.includes(ri);
      return new TableCell({
        width: { size: cols[i], type: WidthType.DXA },
        shading: {
          type: ShadingType.CLEAR,
          fill: warn ? WARN_BG : (ri % 2 ? ALT_BG : "FFFFFF"),
          color: "auto",
        },
        margins: { top: 60, bottom: 60, left: 80, right: 80 },
        children: [cellPara(c, {
          bold: opts.boldCols && opts.boldCols.includes(i),
          align: (opts.centerCols && opts.centerCols.includes(i)) ? AlignmentType.CENTER : undefined,
        })],
      });
    }),
  }));

  return new Table({
    columnWidths: cols,
    width: { size: USABLE, type: WidthType.DXA },
    rows: [headRow, ...bodyRows],
  });
}

